"use strict";

const fs = require("fs");
const path = require("path");
const { collectDocs } = require("../lib/core");
const { moduleDocs } = require("./navigation");
const { syncRuntime } = require("./project");

const MARKER = "AUTO-GENERATED by ai-project-continuity; edit canonical docs and run sync.";
const PREVIOUS_MARKER = "AUTO-GENERATED by ai-project-continuity; edit AGENTS.md and run sync.";
const LEGACY_MARKERS = ["AUTO-GENERATED by `uada sync`", "AUTO-GENERATED by uada sync"];

function removeIfGenerated(file, markers) {
  if (!fs.existsSync(file)) return false;
  const text = fs.readFileSync(file, "utf8");
  if (!markers.some(marker => text.includes(marker))) return false;
  fs.unlinkSync(file);
  return true;
}

function sync(root) {
  const agents = fs.readFileSync(path.join(root, "AGENTS.md"), "utf8");
  fs.writeFileSync(path.join(root, "CLAUDE.md"), `<!-- ${MARKER} -->\n${agents}`, "utf8");
  const cursorDir = path.join(root, ".cursor", "rules");
  fs.mkdirSync(cursorDir, { recursive: true });
  fs.writeFileSync(path.join(cursorDir, "project-continuity.mdc"), `---\ndescription: Project documentation router generated from AGENTS.md\nglobs:\nalwaysApply: true\n---\n<!-- ${MARKER} -->\n${agents}`, "utf8");
  const modules = moduleDocs(collectDocs(root));
  const expected = new Set();
  for (const moduleDoc of modules) {
    const name = `module-${moduleDoc.fm.id}.mdc`;
    expected.add(name);
    const globs = Array.isArray(moduleDoc.fm.globs) ? moduleDoc.fm.globs.join(",") : "";
    const content = `---\ndescription: ${moduleDoc.fm.summary || moduleDoc.fm.id}\nglobs: ${globs}\nalwaysApply: false\n---\n<!-- ${MARKER} -->\n${moduleDoc.body}`;
    fs.writeFileSync(path.join(cursorDir, name), content, "utf8");
  }
  for (const file of fs.readdirSync(cursorDir)) {
    const full = path.join(cursorDir, file);
    if (/^module-.+\.mdc$/.test(file) && !expected.has(file)) {
      if (removeIfGenerated(full, [MARKER, PREVIOUS_MARKER])) console.log(`removed stale .cursor/rules/${file}`);
      else console.warn(`WARN preserved unrecognized Cursor rule ${file}`);
    }
    if (file === "uada.mdc" || /^mod-.+\.mdc$/.test(file)) {
      if (removeIfGenerated(full, LEGACY_MARKERS)) console.log(`removed legacy .cursor/rules/${file}`);
      else console.warn(`WARN preserved unrecognized legacy-named Cursor rule ${file}`);
    }
  }
  const legacyLlms = path.join(root, "llms.txt");
  if (removeIfGenerated(legacyLlms, ["UADA project. Auto-generated by uada sync."])) console.log("removed legacy generated llms.txt (not a configured target)");
  const runtimeFiles = syncRuntime(root);
  console.log(`synced CLAUDE.md, ${modules.length + 1} Cursor rule(s), and ${runtimeFiles} local runtime file(s)`);
}

module.exports = { MARKER, sync, removeIfGenerated };
